// Regenerates eval/results/provider/summary.md from every run JSON in the folder.
import fs from 'node:fs';
import path from 'node:path';

const mean = values => (values.length ? values.reduce((a, b) => a + b, 0) / values.length : null);
const quantile = (values, q) => {
  if (!values.length) return null;
  const sorted = [...values].sort((a, b) => a - b);
  return sorted[Math.min(sorted.length - 1, Math.max(0, Math.ceil(q * sorted.length) - 1))];
};
const f = (value, digits = 2) => (value === null || value === undefined ? '-' : value.toFixed(digits));
// Windows used to draft the plan prompt (its example folder name is one of life's gold groups).
const PROMPT_WINDOWS = new Set(['dev', 'life']);
const secs = ms => (ms === null ? '-' : (ms / 1000).toFixed(2) + ' s');

export function writeSummary(dir) {
  const files = fs.readdirSync(dir).filter(name => name.endsWith('.json') && name !== 'report.json').sort();
  const groups = new Map();
  for (const file of files) {
    const run = JSON.parse(fs.readFileSync(path.join(dir, file), 'utf8'));
    const sent = run.units.find(unit => unit.requests?.[0])?.requests[0].sent || {};
    const setting = `${run.thinking}${run.effort ? ` / effort ${run.effort}` : ''}`;
    const key = `${run.model}\u0000${run.mode}\u0000${setting}\u0000${sent.note || ''}`;
    if (!groups.has(key)) groups.set(key, { model: run.model, mode: run.mode, setting, note: sent.note || '', units: [], stability: [], cost: 0, files: 0 });
    const group = groups.get(key);
    group.units.push(...run.units);
    group.stability.push(...(run.stability || []).map(item => item.f1));
    group.cost += run.cost_usd || 0;
    group.files += 1;
  }
  const rows = [...groups.values()].sort((a, b) => a.model.localeCompare(b.model) || a.mode.localeCompare(b.mode) || a.setting.localeCompare(b.setting));
  const lines = [
    '# Provider evaluation summary',
    '',
    `Regenerated by \`node eval/run-provider.mjs --summary-only\` from ${files.length} run file(s). Latency is wall time for one window (labels: all batches in parallel). Costs use the price table in \`eval/run-provider.mjs\` (list prices, checked on 22 November 2026).`,
    '',
    `F1 covers tabs with a gold task only, with answers scored as given (\`eval/results/rescore.md\` adds an all-tab score under one applied-result policy). ${[...PROMPT_WINDOWS].join(' and ')} were used to draft the plan prompt, so the mean without them is given beside the mean over every window. Plan stability is pairwise F1 between the two repeats of a window over all tabs, with or without a gold task.`,
    '',
    '| Model | Mode | Thinking / effort | Window runs | Mean F1 | Mean F1 excl. dev, life | p50 latency | p90 latency | Mean output tokens | Cost per window (USD) | Failures | Plan stability F1 (all tabs) |',
    '| --- | --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |'
  ];
  for (const g of rows) {
    const done = g.units.filter(unit => !unit.failed);
    const latencies = done.map(unit => unit.wall_ms);
    const outputs = g.units.map(unit => unit.output_tokens).filter(value => value !== null);
    const cost = g.units.reduce((sum, unit) => sum + (unit.cost_usd || 0), 0);
    lines.push(`| ${g.model} | ${g.mode} | ${g.setting} | ${g.units.length} | ${f(mean(done.map(unit => unit.score.f1)))} | ${f(mean(done.filter(unit => !PROMPT_WINDOWS.has(unit.window)).map(unit => unit.score.f1)))} | ${secs(quantile(latencies, 0.5))} | ${secs(quantile(latencies, 0.9))} | ${f(mean(outputs), 0)} | ${(cost / g.units.length).toFixed(5)} | ${g.units.length - done.length} | ${f(mean(g.stability))} |`);
  }
  lines.push('', '## What was sent for each row', '');
  for (const g of rows) lines.push(`- ${g.model} ${g.mode} ${g.setting}: ${g.note || 'n/a'}`);
  lines.push('', '## Per window', '', '| Model | Mode | Setting | Window | Tabs | Runs | Mean F1 | Mean P | Mean R | Left out (mean) | Groups (mean) | p50 latency | Output tokens |', '| --- | --- | --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |');
  for (const g of rows) {
    const byWindow = new Map();
    for (const unit of g.units) {
      if (!byWindow.has(unit.window)) byWindow.set(unit.window, []);
      byWindow.get(unit.window).push(unit);
    }
    for (const [name, units] of [...byWindow].sort()) {
      const done = units.filter(unit => !unit.failed);
      lines.push(`| ${g.model} | ${g.mode} | ${g.setting} | ${name} | ${units[0].tabs} | ${units.length} | ${f(mean(done.map(u => u.score.f1)))} | ${f(mean(done.map(u => u.score.p)))} | ${f(mean(done.map(u => u.score.r)))} | ${f(mean(done.map(u => u.left_out)), 1)} | ${f(mean(done.map(u => u.groups)), 1)} | ${secs(quantile(done.map(u => u.wall_ms), 0.5))} | ${f(mean(units.map(u => u.output_tokens).filter(v => v !== null)), 0)} |`);
    }
  }
  lines.push('');
  fs.writeFileSync(path.join(dir, 'summary.md'), lines.join('\n'));
}
